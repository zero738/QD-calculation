def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    digest.update(path.read_bytes())
    return digest.hexdigest()


def write_lf(path: Path, text: str, encoding: str = "utf-8") -> None:
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    path.write_bytes(normalized.encode(encoding))


def replace_once(text: str, old: str, new: str, label: str) -> str:
    count = text.count(old)
    if count != 1:
        raise RuntimeError(f"expected exactly one {label}; found {count}")
    return text.replace(old, new, 1)


def transform_input(task_id: str, spec: dict) -> str:
    source = ROOT / "research_lite" / "inputs" / spec["source"]
    text = source.read_text(encoding="utf-8")
    text = re.sub(
        r"^# Generated by .*?$",
        "# Generated for SCNet East China 1 Kunshan; target CP2K 2024.1.",
        text,
        count=1,
        flags=re.MULTILINE,
    )
    text = re.sub(
        r"^# PROFILE .*?$",
        "# Fixed-geometry research-lite prototype; not publication-converged.",
        text,
        count=1,
        flags=re.MULTILINE,
    )
    text = re.sub(
        r"(?m)^\s*PROJECT\s+\S+\s*$",
        f"  PROJECT {spec['project']}",
        text,
        count=1,
    )
    text = text.replace(
        "CP2K 2024.3 PDOS/LDOS support",
        "the target CP2K 2024.1 PDOS/LDOS path",
    )

    if task_id.startswith("cu2te_bulk"):
        block_re = re.compile(r"\n\s*&KPOINTS\s*\n.*?&END KPOINTS\s*\n", re.S | re.I)
        match = block_re.search(text)
        if not match:
            raise RuntimeError("bulk source input does not contain one KPOINTS block")
        if task_id == "cu2te_bulk_gamma":
            text = block_re.sub(
                "\n    # Implicit Gamma: no explicit KPOINTS block.\n",
                text,
                count=1,
            )
        else:
            size = task_id[-3]
            replacement = (
                "\n    &KPOINTS\n"
                f"      SCHEME MONKHORST-PACK {size} {size} {size}\n"
                "    &END KPOINTS\n"
            )
            text = block_re.sub(replacement, text, count=1)
        upper = text.upper()
        for forbidden in ("&DOS", "&PDOS", "&LDOS", "V_HARTREE_CUBE", "E_DENSITY_CUBE"):
            if forbidden in upper:
                raise RuntimeError(f"energy-only bulk input contains {forbidden}")

    if task_id in {"H1", "H2"}:
        text = replace_once(text, "MAX_SCF 150", "MAX_SCF 250", "MAX_SCF")
        text = replace_once(text, "ADDED_MOS 40", "ADDED_MOS 100", "ADDED_MOS")
        text = replace_once(text, "ALPHA 0.15", "ALPHA 0.08", "MIXING ALPHA")
        text = replace_once(text, "NBROYDEN 8", "NBROYDEN 12", "NBROYDEN")
        text = replace_once(text, "NLUMO 40", "NLUMO 100", "PDOS NLUMO")

    if "EPS_SCF 1e-06" not in text:
        raise RuntimeError(f"{task_id}: EPS_SCF was changed unexpectedly")
    if "RUN_TYPE ENERGY" not in text:
        raise RuntimeError(f"{task_id}: only fixed-geometry ENERGY runs are allowed")
    return text.rstrip() + "\n"


def write_inputs() -> None:
    for task_id, spec in TASKS.items():
        destination_dir = PACKAGE / "inputs" / spec["input_dir"]
        destination_dir.mkdir(parents=True, exist_ok=True)
        destination = destination_dir / spec["input_name"]
        write_lf(destination, transform_input(task_id, spec))
        source_structure = SOURCE_INPUTS / spec["input_dir"] / "structure.extxyz"
        destination_structure = destination_dir / "structure.extxyz"
        write_lf(
            destination_structure,
            source_structure.read_text(encoding="utf-8"),
        )


