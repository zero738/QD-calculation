def validate_paths() -> None:
    bad = []
    for path in PACKAGE.rglob("*"):
        relative = path.relative_to(PACKAGE).as_posix()
        if any(ord(character) > 127 for character in relative) or " " in relative:
            bad.append(relative)
    if bad:
        raise RuntimeError(f"non-ASCII or space-containing server paths: {bad}")


def write_manifest() -> None:
    validate_paths()
    excluded_roots = {"runs", "results"}
    paths = []
    for path in PACKAGE.rglob("*"):
        if not path.is_file() or path.name == "upload_manifest.txt":
            continue
        relative = path.relative_to(PACKAGE)
        if relative.parts and relative.parts[0] in excluded_roots:
            continue
        if "__pycache__" in relative.parts or path.suffix.lower() == ".pyc":
            continue
        paths.append((relative.as_posix(), sha256(path)))
    lines = [f"{digest}  {relative}" for relative, digest in sorted(paths)]
    write_lf(
        PACKAGE / "upload_manifest.txt",
        "\n".join(lines) + "\n",
        encoding="ascii",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the SCNet CP2K 2024.1 package inputs")
    parser.add_argument(
        "--manifest-only",
        action="store_true",
        help="refresh upload_manifest.txt after authored package files are updated",
    )
    args = parser.parse_args()
    PACKAGE.mkdir(parents=True, exist_ok=True)
    if not args.manifest_only:
        write_inputs()
        write_package_config()
    write_manifest()
    print(PACKAGE)
    return 0


